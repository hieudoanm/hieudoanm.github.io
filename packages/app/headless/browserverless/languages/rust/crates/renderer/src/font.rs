#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn font_creation() {
        let font = BitmapFont::new();
        assert_eq!(font.glyph_width(), 8);
        assert_eq!(font.glyph_height(), 8);
    }

    #[test]
    fn text_width_calculation() {
        let font = BitmapFont::new();
        assert_eq!(font.text_width("Hello"), 40);
        assert_eq!(font.text_width(""), 0);
    }

    #[test]
    fn text_height() {
        let font = BitmapFont::new();
        assert_eq!(font.text_height(), 8);
    }

    #[test]
    fn draw_glyph_no_panic() {
        let font = BitmapFont::new();
        let mut img = RgbaImage::new(100, 100);
        let color = Rgba([0, 0, 0, 255]);
        font.draw_glyph(&mut img, 'A', 0, 0, color);
        font.draw_glyph(&mut img, 'B', 10, 10, color);
        font.draw_glyph(&mut img, '!', 20, 20, color);
    }

    #[test]
    fn draw_out_of_bounds_glyph() {
        let font = BitmapFont::new();
        let mut img = RgbaImage::new(10, 10);
        let color = Rgba([0, 0, 0, 255]);
        font.draw_glyph(&mut img, 'A', 100, 100, color);
    }

    #[test]
    fn all_printable_ascii_characters() {
        let font = BitmapFont::new();
        let mut img = RgbaImage::new(800, 100);
        let color = Rgba([0, 0, 0, 255]);

        for ch in 32..=126 {
            let c = ch as u8 as char;
            let x = (ch - 32) * 8;
            font.draw_glyph(&mut img, c, x as i32, 0, color);
        }
    }
}
